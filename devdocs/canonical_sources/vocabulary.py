"""shikumi-contrace の用語集の正本ソース。

``TERM_NNN`` の数値部分は Python 上で各用語を識別するためだけに存在し、
順序、分類、用語名その他の意味を一切表さない。

Shikumi の用語（規定体、記述体、記述器、情報型、実体、検証規則、診断情報、
意味像、焦点など）は、Shikumi の用語集に従い、ここでは再定義しない。
"""

from shikumi_devdoc.norms.common import canonical_source
from shikumi_devdoc.norms.vocabulary import vocabulary


@vocabulary
@canonical_source(
    "shikumi-contrace 用語集",
    filename="GLOSSARY.md",
    merge_policy="local",
    heading="identity",
)
class TERMS:
    """shikumi-contrace の仕様と文書で共有する主要概念の用語。Shikumi の用語は再定義しない。"""

    class TERM_001:
        """
        {{契約}}

        一つの対象型について、その振る舞いの約束を条項の集合として記述した実体（クラス）。対象型の指定と、条項およびメンバーを含む。

        契約はテストのための概念であり、実装の設計に影響を与えるものではない。
        """

    class TERM_002:
        """
        {{対象型}}

        契約が条項の対象とする型。契約自身が定義する構造的な型（Protocol）であり、実装のクラスそのものではない。実装は、契約を import することなく、構造的に対象型へ適合する。
        """

    class TERM_003:
        """
        {{メンバー}}

        対象型のうち、メソッドなど、個別の条項の対象となる要素を表す、契約内の入れ子クラス。Shikumi が扱う粒度がクラスまでであるため、メソッド単位の条項もクラスで表す。対象型が呼び出し可能な型のときは、契約自身がメンバーを表してよい。
        """

    class TERM_004:
        """
        {{条項}}

        契約の中で、一つの約束を一文で述べる実体。クラスとして記述し、docstring を条項文とする。対象型全体に対する条項は契約の直下に、メンバーに対する条項はそのメンバーの下に置く。
        """

    class TERM_005:
        """
        {{条項種別}}

        条項が、事前条件、事後条件、不変条件などのどれであるかを示す情報。標準語彙として事前条件、事後条件、不変条件を用意するが、利用者が独自の種別を加えることを妨げない。
        """

    class TERM_006:
        """
        {{事前条件}}

        対象を呼び出す側が、呼び出す前に満たすべき条件。違反した呼び出しに対する対象の振る舞いも、事前条件の条項として記述できる。
        """

    class TERM_007:
        """
        {{事後条件}}

        対象の呼び出しが成功した後に、対象が保証する条件。
        """

    class TERM_008:
        """
        {{不変条件}}

        対象が、呼び出しの前後を通じて保つ条件。ここでの不変条件は契約における条項の種別であり、Shikumi の用語集にある、Shikumi 自身の意味体系が保つべき不変条件とは別の概念である。
        """

    class TERM_009:
        """
        {{注釈}}

        契約の条項やテストに添える補足情報。判断の理由、境界の意図、注意事項などを、人間と LLM に伝える。実行時に利用するかどうかを問わず、記述されていること自体に意味がある。
        """

    class TERM_010:
        """
        {{関係づけ}}

        テストが、契約のどの条項に対して何をするのかを述べる記述。例えば、条項の違反を確かめる、条項が成り立つことを確かめる、といった関係を、テストの直前に宣言する。
        """

    class TERM_011:
        """
        {{標準語彙}}

        shikumi-contrace が用意する語彙。条項種別、違反時の扱い、関係語、注釈語を含む。標準の語とその意味は、標準語彙の仕様書に定める。
        """

    class TERM_012:
        """
        {{独自語彙}}

        利用者が定義して加える語彙。標準語彙と同じ生成器で作る値であり、標準語彙と同じ位置で使える。shikumi-contrace は、未知の語彙であることを理由に拒否せず、使うために登録も要らない。
        """

    class TERM_013:
        """
        {{束縛}}

        契約の対象型と、実際の実装を結び付けること、およびその記述。契約と実装は互いを知らないため、束縛はテストの側が持つ。
        """

    class TERM_014:
        """
        {{実装}}

        テストの対象となるコード。クラス、関数、module のいずれでもよい。契約を import せず、契約の対象型に構造的に適合する。
        """

    class TERM_015:
        """
        {{適合}}

        実装が、契約の対象型の求める構造（メソッドの署名、属性など）を満たしていること。名前による継承ではなく、構造的部分型による。
        """

    class TERM_016:
        """
        {{契約資産}}

        契約と、契約が定義する対象型を含む、独立した module または package。テストおよび実装とは別に置き、スクラッチでの作り直しなどの際に、契約だけを持ち出せる単位とする。契約資産は、テストにも実装にも依存しない。
        """

    class TERM_017:
        """
        {{本体}}

        shikumi-contrace のうち、特定のテストランナーに依存しない部分。語彙、情報型、記述器、検証規則と、metamk の再エクスポートを含み、pytest を import しない。契約資産が import する shikumi-contrace の部分は、本体に留めることが望ましい。
        """

    class TERM_018:
        """
        {{pytest連携}}

        shikumi-contrace のうち、pytest に依存する任意の部分。本体が付けた情報を、pytest が収集したテストから読み、契約情報の表示など、必要最小限の機能を提供する。導入しなくても、本体の機能は使える。
        """

    class TERM_019:
        """
        {{関係語}}

        テストが、条項に対してどのような姿勢をとるかを表す語。標準の関係語は、条項の種別を繰り返さず、姿勢だけを表す。
        """

    class TERM_020:
        """
        {{注釈語}}

        注釈の性質を表す語。説明、領域、重さ、状態、検証といった観点の語を、標準語彙として用意する。
        """

    class TERM_021:
        """
        {{生成器}}

        関係語、注釈語、条項種別、違反時の扱いの語を作る関数。標準語彙も独自語彙も、同じ生成器で作る。
        """

    class TERM_022:
        """
        {{契約依存}}

        一つの契約の存続または妥当性が、別の契約の存続または妥当性を前提としていることを表す、一方向の関係。依存先の契約が変更または廃止されたとき、依存元の契約は再評価の対象になる。論理的な含意や、依存先の変更による自動的な破棄を意味しない。
        """

    class TERM_023:
        """
        {{違反時の扱い}}

        事前条件を満たさない呼び出しについて、その条項がどこまで振る舞いを約束するかを表す情報。実装が例外、戻り値、プロトコル上の応答などのどの方法で扱うかは、それ自体では規定しない。
        """

    class TERM_024:
        """
        {{境界の型}}

        契約と実装が共有したい値の形（対象型のメソッドの引数や戻り値に現れる Protocol やデータの型）を、契約資産のパッケージの直下の `ports` パッケージに置いたもの。契約資産の一部である。ふるまいは持たず、契約も shikumi-contrace も参照しない。実装がそこから import するかどうかは、実装の自由である。
        """
